package dopaminelite.payment_portal.entity.enums;

/**
 * Enumeration defining the mode in which a student writes their exam papers.
 */
public enum PaperWritingMode {
    /**
     * Student is not currently writing papers.
     */
    NOT_WRITING,

    /**
     * Student writes papers physically at a paper center.
     */
    PHYSICAL,

    /**
     * Student writes papers online/remotely.
     */
    ONLINE
}
